package iot.iot.service;

import iot.iot.entity.CommandLog;
import iot.iot.integration.nodered.NodeRedCommandRequest;
import iot.iot.repository.CommandLogRepository;
import iot.iot.repository.DeviceRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

@Service
public class CommandAuditService {
    private final CommandLogRepository commands;
    private final DeviceRepository devices;
    public CommandAuditService(CommandLogRepository commands, DeviceRepository devices) {
        this.commands = commands; this.devices = devices;
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public void recordConfirmed(String deviceId, NodeRedCommandRequest request, String username) {
        CommandLog log = new CommandLog();
        log.setDevice(devices.getReferenceById(deviceId));
        log.setTarget(request.target().name()); log.setAction(request.action().name());
        log.setTriggerBy(username);
        commands.saveAndFlush(log); // DATETIME default is generated by MySQL.
    }
}
